// cobe → your brand. Writes brand-globe.js (+ .d.ts): cobe's colour props for a
// light and a dark globe, and spinGlobe(), a render loop (cobe 2 has none). Also
// writes brand-globe.css for marker labels that follow the globe.

import { readFile } from 'node:fs/promises';

const template = (name) => readFile(new URL(`./template/${name}`, import.meta.url), 'utf8');

/** @param {ReturnType<typeof import('../../lib/brand.mjs').resolveBrand>} brand */
export default async function adapt(brand, { colour }) {
  const { mix, rgb255 } = colour;
  // cobe takes colours as [r, g, b] from 0 to 1.
  const v = (c) => rgb255(c).map((x) => +(x / 255).toFixed(3));
  const { light: l, dark: d } = brand;
  const out = {
    // Light: a globe the colour of your page, land dots in shade, markers and arcs in primary.
    // The halo is your muted surface, so the globe sits on the page rather than glowing.
    light: { dark: 0, diffuse: 1.5, mapBrightness: 10, baseColor: v(l.background), markerColor: v(l.primary), arcColor: v(l.primary), glowColor: v(l.muted) },
    // Dark: dots lit from a base between your dark page and its text; the halo is primary, faintly.
    dark: { dark: 1, diffuse: 1.2, mapBrightness: 8, baseColor: v(mix(d.background, d.foreground, 0.35)), markerColor: v(d.primary), arcColor: v(d.primary), glowColor: v(mix(d.background, d.primary, 0.35)) },
  };
  const js = (await template('brand-globe.js')).replace(
    /\/\* brand:start \*\/[\s\S]*?\/\* brand:end \*\//,
    () => `/* brand:start */\n// ${brand.name}\nexport const brandGlobe = {\n  light: ${JSON.stringify(out.light)},\n  dark: ${JSON.stringify(out.dark)},\n};\n/* brand:end */`,
  );
  const css = `/* Generated by \`pa add cobe --brand …\` (${brand.name.replaceAll('*/', '* /')}). Labels that ride on cobe's markers.
   Give a marker an id ("london") and pin a label to it with style="--id: --cobe-london; --seen: var(--cobe-visible-london, 0)". */
.globe-wrap { position: relative; }  /* must be exactly the canvas's box: cobe's anchors are placed in % of it */
.globe-label {
  position: absolute; position-anchor: var(--id); bottom: anchor(top); left: anchor(center); translate: -50% -4px;
  opacity: var(--seen); filter: blur(calc((1 - var(--seen)) * 4px)); transition: opacity .3s, filter .3s;
  background: ${l.primary}; color: ${l.primaryForeground}; border-radius: calc(${brand.radius} / 2);
  font: 500 11px/1 ${brand.fonts.mono}; letter-spacing: .06em; text-transform: uppercase; white-space: nowrap; padding: 4px 6px;
}
.dark .globe-label, [data-theme="dark"] .globe-label { background: ${d.primary}; color: ${d.primaryForeground}; }
`;
  return {
    files: { 'brand-globe.js': js, 'brand-globe.d.ts': await template('brand-globe.d.ts'), 'brand-globe.css': css },
    usage: `
import { spinGlobe } from '{{dir}}/brand-globe';
import '{{dir}}/brand-globe.css';

// <div class="globe-wrap" style="width:500px;height:500px"><canvas style="width:100%;height:100%"></canvas>
//   <span class="globe-label" style="--id: --cobe-london; --seen: var(--cobe-visible-london, 0)">London</span></div>
const { stop } = spinGlobe(canvas, {
  theme: 'light',                       // or 'dark'
  markers: [{ id: 'london', location: [51.51, -0.13], size: 0.04 }],
  arcs: [{ from: [51.51, -0.13], to: [40.71, -74.01] }],
});`,
  };
}
